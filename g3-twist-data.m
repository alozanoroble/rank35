// ---------------- D = g(3), Mestre's polynomial ----------------
mestre_g := func< t | -a*b*(t^2+1)*(b^2*(t^4+t^2+1)^3 + a^3*t^4*(t^2+1)^2) >;
D := Integers()!mestre_g(3);                                 // 411 digits, D > 0
Dfac := [<2,8>, <3,12>, <5,15>, <7,4>, <11,8>, <29,1>, <67,1>, <191,1>, <269,1>, <521,1>, <709,1>, <37847,1>];
C := D div &*[pe[1]^pe[2] : pe in Dfac];
assert D eq C * &*[pe[1]^pe[2] : pe in Dfac];
assert forall{p : p in PrimesUpTo(10^6) | C mod p ne 0};    // C: 362 digits, no factor < 10^6
assert not IsSquare(C) and not IsProbablePrime(C);           // composite, factorization unknown
// square class: d = 5*29*67*191*269*521*709*37847 * (square-free part of C)

// ---------------- the twist and Mestre's two points ----------------
ED := EllipticCurve([0, 0, 0, a*D^2, b*D^3]);                // E^D, the twist of Es by D
t := 3;
P := ED ! [ -(b/a)*(t^2+t+1)*(t^2-t+1)/(t^2+1)*D,       D^2/(a^2*(t^2+1)^2) ];
Q := ED ! [ -(b/a)*(t^2+t+1)*(t^2-t+1)/(t^2*(t^2+1))*D, D^2/(a^2*t^3*(t^2+1)^2) ];

// independence: X - D*theta is a non-square in Q(theta) for P, Q and P+Q (Legendre witnesses)
witness := function(Xs, l, r)
    v := &*[(GF(l)!X) - (GF(l)!D)*(GF(l)!r) : X in Xs];
    return (GF(l)!r)^3 + (GF(l)!a)*(GF(l)!r) + (GF(l)!b) eq 0 and v ne 0 and not IsSquare(v);
end function;
assert witness([P[1]], 61, 15);
assert witness([Q[1]], 47, 37);
assert witness([P[1], Q[1]], 47, 37);
assert IsIrreducible(PolynomialRing(Integers())![b, a, 0, 1]);   // no 2-torsion

// root number W(E^D) = -1 via local representatives at S and the Jacobi symbol (-1/M)
S := Sort(SetToSequence(Set(Nbad) join {2, 3}));
localrep := function(p)
    v := Valuation(D, p); u := D div p^v;
    if p eq 2 then r := u mod 8;
    else r := LegendreSymbol(u mod p, p) eq 1 select 1 else Min([k : k in [2..200] | LegendreSymbol(k, p) eq -1]); end if;
    return p^(v mod 2) * r;
end function;
M := D; for p in S do while M mod p eq 0 do M div:= p; end while; end for;
WD := -1 * &*[RootNumber(EllipticCurve([0,0,0,a*localrep(p)^2,b*localrep(p)^3]), p) : p in S] * JacobiSymbol(-1, M);
assert WD eq -1;

// ---------------- the two extra points over K = Q(sqrt D) on E ----------------
K<s> := NumberField(PolynomialRing(Rationals())![-D, 0, 1]);
EK := BaseChange(E, K);
toE := function(X, Y)        // (X, Y) on E^D  ->  point on E over K
    xs := X / D; c := Y / D^2;                               // short model: (xs, c*s)
    x := (xs - 3)/36;
    return EK ! [x, -x/2 + (c/216)*s];
end function;
P33 := toE(P[1], P[2]);
P34 := toE(Q[1], Q[2]);
// sigma(P33) = -P33 and sigma(P34) = -P34: they lie in the minus part, independent of E(Q)
sig := hom< K -> K | -s >;
assert EK ! [sig(P33[1]), sig(P33[2])] eq -P33;
assert EK ! [sig(P34[1]), sig(P34[2])] eq -P34;

